# =========================================================
# LOAD MODEL
# =========================================================

@st.cache_resource
def load_model():
    return joblib.load(
        "disease_prediction_logistic_regression.pkl"
    )


logistic_model = load_model()


# =========================================================
# HEADER
# =========================================================

st.title("🩺 Disease Prediction Dashboard")

st.write(
    "Enter the patient information below to generate an "
    "ML-based disease prediction."
)

st.info(
    "This prediction is generated by a machine-learning model "
    "and should not be treated as a medical diagnosis."
)


# =========================================================
# PATIENT INFORMATION
# =========================================================

st.subheader("👤 Patient Information")

col1, col2, col3 = st.columns(3)


with col1:

    age = st.number_input(
        "Age",
        min_value=1,
        max_value=120,
        value=50,
        step=1
    )

    gender = st.selectbox(
        "Gender",
        ["Male", "Female"]
    )

    bmi = st.number_input(
        "BMI",
        min_value=10.0,
        max_value=60.0,
        value=25.0,
        step=0.1
    )


with col2:

    blood_pressure = st.number_input(
        "Blood Pressure (mmHg)",
        min_value=1,
        max_value=250,
        value=120,
        step=1
    )

    cholesterol = st.number_input(
        "Cholesterol (mg/dL)",
        min_value=1,
        max_value=500,
        value=200,
        step=1
    )

    glucose = st.number_input(
        "Glucose (mg/dL)",
        min_value=1,
        max_value=500,
        value=100,
        step=1
    )


with col3:

    heart_rate = st.number_input(
        "Heart Rate (bpm)",
        min_value=1,
        max_value=220,
        value=72,
        step=1
    )

    smoking = st.selectbox(
        "Smoking",
        ["Yes", "No"]
    )

    exercise_level = st.selectbox(
        "Exercise Level",
        ["Low", "Moderate", "High"]
    )


# =========================================================
# CREATE PATIENT DATA
# =========================================================

new_patient = pd.DataFrame({
    "Age": [age],
    "Gender": [gender],
    "BMI": [bmi],
    "Blood_Pressure_mmHg": [blood_pressure],
    "Cholesterol_mg_dL": [cholesterol],
    "Glucose_mg_dL": [glucose],
    "Heart_Rate_bpm": [heart_rate],
    "Smoking": [smoking],
    "Exercise_Level": [exercise_level]
})


# =========================================================
# INPUT VALIDATION
# =========================================================

valid_input = (
    1 <= age <= 120
    and 10 <= bmi <= 60
    and 1 <= blood_pressure <= 250
    and 1 <= cholesterol <= 500
    and 1 <= glucose <= 500
    and 1 <= heart_rate <= 220
)


# =========================================================
# PREDICT BUTTON
# =========================================================

st.divider()

predict_button = st.button(
    "🔍 Predict Disease",
    type="primary",
    use_container_width=True
)


# =========================================================
# PREDICTION
# =========================================================

if predict_button:

    if not valid_input:

        st.error(
            "Invalid input. Please enter values within the "
            "allowed ranges."
        )

    else:

        # =================================================
        # MODEL PREDICTION
        # =================================================

        prediction = logistic_model.predict(
            new_patient
        )

        probability = logistic_model.predict_proba(
            new_patient
        )

        predicted_class = prediction[0]


        # =================================================
        # RESULT
        # =================================================

        st.subheader("📊 Prediction Result")

        if predicted_class == "Disease":

            st.error(
                "⚠️ Model Prediction: Disease"
            )

        else:

            st.success(
                "✅ Model Prediction: No Disease"
            )


        # =================================================
        # PROBABILITY CALCULATION
        # =================================================

        st.subheader("📈 Prediction Probability")

        classes = logistic_model.classes_

        probability_data = {}

        for class_name, prob in zip(
            classes,
            probability[0]
        ):

            probability_data[class_name] = prob


        # Disease probability

        if "Disease" in probability_data:

            disease_probability = (
                probability_data["Disease"] * 100
            )

        else:

            disease_probability = 0


        # No Disease probability

        if "No Disease" in probability_data:

            no_disease_probability = (
                probability_data["No Disease"] * 100
            )

        else:

            no_disease_probability = 0


        # =================================================
        # METRICS
        # =================================================

        result_col1, result_col2 = st.columns(2)


        with result_col1:

            st.metric(
                "🩸 Disease Probability",
                f"{disease_probability:.2f}%"
            )


        with result_col2:

            st.metric(
                "💚 No Disease Probability",
                f"{no_disease_probability:.2f}%"
            )


        # =================================================
        # DONUT CHART
        # =================================================

        st.subheader("📊 Prediction Probability")

        fig = go.Figure(
            data=[
                go.Pie(
                    labels=[
                        "Disease",
                        "No Disease"
                    ],
                    values=[
                        disease_probability,
                        no_disease_probability
                    ],
                    hole=0.60,
                    textinfo="label+percent",
                    textposition="outside",

                    marker=dict(
                        colors=[
                            "#ef4444",
                            "#22c55e"
                        ],
                        line=dict(
                            color="#ffffff",
                            width=3
                        )
                    ),

                    hovertemplate=(
                        "<b>%{label}</b><br>"
                        "Probability: %{value:.2f}%"
                        "<extra></extra>"
                    )
                )
            ]
        )


        fig.update_layout(

            height=400,

            margin=dict(
                l=20,
                r=20,
                t=30,
                b=20
            ),

            showlegend=True,

            legend=dict(
                orientation="h",
                yanchor="bottom",
                y=-0.05,
                xanchor="center",
                x=0.5
            ),

            paper_bgcolor="rgba(0,0,0,0)",

            plot_bgcolor="rgba(0,0,0,0)"
        )


        st.plotly_chart(
            fig,
            use_container_width=True
        )


        # =================================================
        # PATIENT DATA
        # =================================================

        st.subheader("📋 Patient Information Used")

        st.dataframe(
            new_patient,
            use_container_width=True,
            hide_index=True
        )